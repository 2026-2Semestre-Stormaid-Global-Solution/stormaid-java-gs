-- 1. Tabela de Auditoria para os Triggers
CREATE TABLE TB_STORMAID_AUDIT_LOG (
                                       AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       TABLE_NAME VARCHAR2(100),
                                       OPERATION_TYPE VARCHAR2(20),
                                       RECORD_ID NUMBER,
                                       LOG_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP,
                                       USER_DESCRIPTION VARCHAR2(100)
);

-- 2. Funções PL/SQL
CREATE OR REPLACE FUNCTION FN_COUNT_CITIZEN_INCIDENTS(p_citizen_id IN NUMBER)
RETURN NUMBER IS
    v_total NUMBER;
BEGIN
SELECT COUNT(*) INTO v_total
FROM TB_INCIDENT_REPORT
WHERE CITIZEN_ID = p_citizen_id;

RETURN NVL(v_total, 0);
END FN_COUNT_CITIZEN_INCIDENTS;
/

CREATE OR REPLACE FUNCTION FN_COUNT_RISKS_BY_CATEGORY(p_category IN VARCHAR2)
RETURN NUMBER IS
    v_total NUMBER;
BEGIN
SELECT COUNT(*) INTO v_total
FROM TB_COMMUNITY_RISK_REPORT
WHERE RISK_CATEGORY = p_category;

RETURN NVL(v_total, 0);
END FN_COUNT_RISKS_BY_CATEGORY;
/

-- 3. Procedures PL/SQL
CREATE OR REPLACE PROCEDURE PR_ADD_COMMUNITY_RISK (
    p_title         IN VARCHAR2,
    p_description   IN VARCHAR2,
    p_category      IN VARCHAR2,
    p_latitude      IN NUMBER,
    p_longitude     IN NUMBER,
    p_citizen_id    IN NUMBER
) AS
BEGIN
INSERT INTO TB_COMMUNITY_RISK_REPORT (
    ID, TITLE, DESCRIPTION, RISK_CATEGORY, LATITUDE, LONGITUDE, CITIZEN_ID, CREATED_AT, STATUS
) VALUES (
             SEQ_COMMUNITY_RISK.NEXTVAL, p_title, p_description, p_category, p_latitude, p_longitude, p_citizen_id, SYSTIMESTAMP, 'PENDING'
         );
COMMIT;
END PR_ADD_COMMUNITY_RISK;
/

CREATE OR REPLACE PROCEDURE PR_UPDATE_RISK_STATUS (
    p_risk_id   IN NUMBER,
    p_status    IN VARCHAR2
) AS
BEGIN
UPDATE TB_COMMUNITY_RISK_REPORT
SET STATUS = p_status, UPDATED_AT = SYSTIMESTAMP
WHERE ID = p_risk_id;
COMMIT;
END PR_UPDATE_RISK_STATUS;
/

-- 4. Pacotes PL/SQL (Specification e Body)
CREATE OR REPLACE PACKAGE PKG_STORMAID_INCIDENTS AS
    FUNCTION GET_INCIDENT_STATUS(p_incident_id IN NUMBER) RETURN VARCHAR2;
    PROCEDURE CLOSE_INCIDENT(p_incident_id IN NUMBER);
END PKG_STORMAID_INCIDENTS;
/

CREATE OR REPLACE PACKAGE BODY PKG_STORMAID_INCIDENTS AS
    FUNCTION GET_INCIDENT_STATUS(p_incident_id IN NUMBER) RETURN VARCHAR2 IS
        v_status VARCHAR2(50);
BEGIN
SELECT PUBLIC_STATUS INTO v_status FROM TB_INCIDENT_REPORT WHERE ID = p_incident_id;
RETURN v_status;
EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN 'NOT_FOUND';
END GET_INCIDENT_STATUS;

    PROCEDURE CLOSE_INCIDENT(p_incident_id IN NUMBER) IS
BEGIN
UPDATE TB_INCIDENT_REPORT SET PUBLIC_STATUS = 'RESOLVED', UPDATED_AT = SYSTIMESTAMP WHERE ID = p_incident_id;
COMMIT;
END CLOSE_INCIDENT;
END PKG_STORMAID_INCIDENTS;
/

CREATE OR REPLACE PACKAGE PKG_STORMAID_PREVENTION AS
    FUNCTION CHECK_COMMUNITY_ALERT(p_risk_id IN NUMBER) RETURN VARCHAR2;
END PKG_STORMAID_PREVENTION;
/

CREATE OR REPLACE PACKAGE BODY PKG_STORMAID_PREVENTION AS
    FUNCTION CHECK_COMMUNITY_ALERT(p_risk_id IN NUMBER) RETURN VARCHAR2 IS
        v_cat VARCHAR2(50);
BEGIN
SELECT RISK_CATEGORY INTO v_cat FROM TB_COMMUNITY_RISK_REPORT WHERE ID = p_risk_id;
IF v_cat = 'CLIMATE_DISASTER' THEN
            RETURN 'HIGH_ALERT';
ELSE
            RETURN 'STANDARD_MONITORING';
END IF;
EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN 'UNKNOWN';
END CHECK_COMMUNITY_ALERT;
END PKG_STORMAID_PREVENTION;
/

-- 5. Triggers de Auditoria
CREATE OR REPLACE TRIGGER TRG_AUDIT_INCIDENT
AFTER INSERT OR UPDATE ON TB_INCIDENT_REPORT
                           FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO TB_STORMAID_AUDIT_LOG (TABLE_NAME, OPERATION_TYPE, RECORD_ID, USER_DESCRIPTION)
        VALUES ('TB_INCIDENT_REPORT', 'INSERT', :NEW.ID, 'Novo incidente registado no sistema');
    ELSIF UPDATING THEN
        INSERT INTO TB_STORMAID_AUDIT_LOG (TABLE_NAME, OPERATION_TYPE, RECORD_ID, USER_DESCRIPTION)
        VALUES ('TB_INCIDENT_REPORT', 'UPDATE', :NEW.ID, 'Atualização de status do incidente');
END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDIT_RISK
AFTER INSERT OR UPDATE ON TB_COMMUNITY_RISK_REPORT
                           FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO TB_STORMAID_AUDIT_LOG (TABLE_NAME, OPERATION_TYPE, RECORD_ID, USER_DESCRIPTION)
        VALUES ('TB_COMMUNITY_RISK_REPORT', 'INSERT', :NEW.ID, 'Novo risco comunitário reportado');
    ELSIF UPDATING THEN
        INSERT INTO TB_STORMAID_AUDIT_LOG (TABLE_NAME, OPERATION_TYPE, RECORD_ID, USER_DESCRIPTION)
        VALUES ('TB_COMMUNITY_RISK_REPORT', 'UPDATE', :NEW.ID, 'Atualização do risco comunitário');
END IF;
END;
