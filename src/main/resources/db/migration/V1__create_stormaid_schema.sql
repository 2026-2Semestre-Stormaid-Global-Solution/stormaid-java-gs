CREATE TABLE TB_STORMAID_USER (
                                  USER_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                                  FULL_NAME VARCHAR2(150 CHAR) NOT NULL,
                                  EMAIL VARCHAR2(150 CHAR) NOT NULL,
                                  PHONE_NUMBER VARCHAR2(20 CHAR) NOT NULL,
                                  PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
                                  STATUS VARCHAR2(20 CHAR) NOT NULL,
                                  CREATED_AT TIMESTAMP(6) NOT NULL,
                                  UPDATED_AT TIMESTAMP(6) NOT NULL,
                                  CONSTRAINT PK_STORMAID_USER PRIMARY KEY (USER_ID),
                                  CONSTRAINT UK_STORMAID_USER_EMAIL UNIQUE (EMAIL),
                                  CONSTRAINT CK_STORMAID_USER_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'BLOCKED'))
);

CREATE TABLE TB_STORMAID_ROLE (
                                  ROLE_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                                  ROLE_NAME VARCHAR2(30 CHAR) NOT NULL,
                                  CONSTRAINT PK_STORMAID_ROLE PRIMARY KEY (ROLE_ID),
                                  CONSTRAINT UK_STORMAID_ROLE_NAME UNIQUE (ROLE_NAME)
);

CREATE TABLE TB_STORMAID_USER_ROLE (
                                       USER_ID NUMBER(19,0) NOT NULL,
                                       ROLE_ID NUMBER(19,0) NOT NULL,
                                       CONSTRAINT PK_STORMAID_USER_ROLE PRIMARY KEY (USER_ID, ROLE_ID),
                                       CONSTRAINT FK_STORMAID_USER_ROLE_USER FOREIGN KEY (USER_ID) REFERENCES TB_STORMAID_USER(USER_ID),
                                       CONSTRAINT FK_STORMAID_USER_ROLE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES TB_STORMAID_ROLE(ROLE_ID)
);

CREATE TABLE TB_STORMAID_CITIZEN_PROFILE (
                                             CITIZEN_PROFILE_ID NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY,
                                             USER_ID NUMBER(19,0) NOT NULL,
                                             STREET VARCHAR2(150 CHAR),
                                             ADDRESS_NUMBER VARCHAR2(20 CHAR),
                                             COMPLEMENT VARCHAR2(100 CHAR),
                                             NEIGHBORHOOD VARCHAR2(100 CHAR),
                                             POSTAL_CODE VARCHAR2(8 CHAR),
                                             CITY VARCHAR2(100 CHAR),
                                             STATE VARCHAR2(2 CHAR),
                                             REFERENCE_POINT VARCHAR2(250 CHAR),
                                             MOBILITY_STATUS VARCHAR2(30 CHAR),
                                             HAS_VISUAL_IMPAIRMENT NUMBER(1,0),
                                             HAS_HEARING_IMPAIRMENT NUMBER(1,0),
                                             DEPENDS_ON_EQUIPMENT NUMBER(1,0),
                                             EQUIPMENT_DESCRIPTION VARCHAR2(250 CHAR),
                                             ACCESSIBILITY_NOTES VARCHAR2(500 CHAR),
                                             EMERGENCY_CONTACT_NAME VARCHAR2(120 CHAR),
                                             EMERGENCY_CONTACT_PHONE VARCHAR2(20 CHAR),
                                             EMERGENCY_CONTACT_RELATIONSHIP VARCHAR2(40 CHAR),
                                             UPDATED_AT TIMESTAMP(6),
                                             CONSTRAINT PK_STORMAID_CITIZEN_PROFILE PRIMARY KEY (CITIZEN_PROFILE_ID),
                                             CONSTRAINT FK_STORMAID_CITIZEN_USER FOREIGN KEY (USER_ID) REFERENCES TB_STORMAID_USER(USER_ID),
                                             CONSTRAINT UK_STORMAID_CITIZEN_USER UNIQUE (USER_ID)
);